// AdminServiceHandler is an implementation of the toll.admin.v1.AdminService service.
type AdminServiceHandler interface {
	// GET /api/usage
	GetUsage(context.Context, *connect.Request[v1.GetUsageRequest]) (*connect.Response[v1.GetUsageResponse], error)
	// GET /api/requests
	ListRequests(context.Context, *connect.Request[v1.ListRequestsRequest]) (*connect.Response[v1.ListRequestsResponse], error)
	// GET /api/requests/{id}
	GetRequest(context.Context, *connect.Request[v1.GetRequestRequest]) (*connect.Response[v1.RequestDetail], error)
	// Time-bucketed usage aggregates with optional group split and
	// previous-period compare.
	GetUsageSeries(context.Context, *connect.Request[v1.GetUsageSeriesRequest]) (*connect.Response[v1.GetUsageSeriesResponse], error)
	// Server-fed filter dropdown values (distinct models/keys).
	ListFilterValues(context.Context, *connect.Request[v1.ListFilterValuesRequest]) (*connect.Response[v1.ListFilterValuesResponse], error)
	// GET /api/providers
	ListProviders(context.Context, *connect.Request[v1.ListProvidersRequest]) (*connect.Response[v1.ListProvidersResponse], error)
	// POST /api/providers
	CreateProvider(context.Context, *connect.Request[v1.CreateProviderRequest]) (*connect.Response[v1.CreateProviderResponse], error)
	// POST /api/providers/{name}/disable + .../enable (via `disabled`)
	UpdateProvider(context.Context, *connect.Request[v1.UpdateProviderRequest]) (*connect.Response[v1.Provider], error)
	// DELETE /api/providers/{name}
	DeleteProvider(context.Context, *connect.Request[v1.DeleteProviderRequest]) (*connect.Response[emptypb.Empty], error)
	// GET /api/models
	ListModels(context.Context, *connect.Request[v1.ListModelsRequest]) (*connect.Response[v1.ListModelsResponse], error)
	// POST /api/models/refresh. Synchronous, like today: it fans out one
	// bounded fetch per provider sequentially. If this ever outgrows client
	// deadlines, the migration path is a server-streamed
	// RefreshModels(RefreshModelsRequest) returns (stream RefreshModelsProgress)
	// — same request message, so that is a v2-only signature change.
	RefreshModels(context.Context, *connect.Request[v1.RefreshModelsRequest]) (*connect.Response[v1.RefreshModelsResponse], error)
	// POST /api/models/{id}/disable + .../enable + PUT .../alias
	// (via `disabled` / `alias`)
	UpdateModel(context.Context, *connect.Request[v1.UpdateModelRequest]) (*connect.Response[v1.Model], error)
	// DELETE /api/models/{id}
	DeleteModel(context.Context, *connect.Request[v1.DeleteModelRequest]) (*connect.Response[emptypb.Empty], error)
	// GET /api/config
	ExportConfig(context.Context, *connect.Request[emptypb.Empty]) (*connect.Response[v1.ExportConfigResponse], error)
	// GET /api/settings
	GetSettings(context.Context, *connect.Request[emptypb.Empty]) (*connect.Response[v1.Settings], error)
	// PUT /api/settings
	UpdateSettings(context.Context, *connect.Request[v1.UpdateSettingsRequest]) (*connect.Response[v1.Settings], error)
	// GET /api/profiles
	ListProfiles(context.Context, *connect.Request[v1.ListProfilesRequest]) (*connect.Response[v1.ListProfilesResponse], error)
	// POST /api/profiles
	CreateProfile(context.Context, *connect.Request[v1.CreateProfileRequest]) (*connect.Response[v1.Profile], error)
	// PUT /api/profiles/{name}
	UpdateProfile(context.Context, *connect.Request[v1.UpdateProfileRequest]) (*connect.Response[v1.Profile], error)
	// DELETE /api/profiles/{name}
	DeleteProfile(context.Context, *connect.Request[v1.DeleteProfileRequest]) (*connect.Response[emptypb.Empty], error)
	// GET /api/keys
	ListKeys(context.Context, *connect.Request[v1.ListKeysRequest]) (*connect.Response[v1.ListKeysResponse], error)
	// POST /api/keys (the plaintext secret is returned exactly once)
	CreateKey(context.Context, *connect.Request[v1.CreateKeyRequest]) (*connect.Response[v1.CreateKeyResponse], error)
	// PUT /api/keys/{name} + .../pause + .../resume
	// (via `new_name` / `profile` / `paused`)
	UpdateKey(context.Context, *connect.Request[v1.UpdateKeyRequest]) (*connect.Response[v1.VirtualKey], error)
	// New (no route today): fresh secret under the same name and profile,
	// old material dead immediately.
	RotateKey(context.Context, *connect.Request[v1.RotateKeyRequest]) (*connect.Response[v1.RotateKeyResponse], error)
	// POST /api/keys/{name}/revoke (one-way; not an Update field on purpose)
	RevokeKey(context.Context, *connect.Request[v1.RevokeKeyRequest]) (*connect.Response[emptypb.Empty], error)
	// DELETE /api/keys/{name}
	DeleteKey(context.Context, *connect.Request[v1.DeleteKeyRequest]) (*connect.Response[emptypb.Empty], error)
}

