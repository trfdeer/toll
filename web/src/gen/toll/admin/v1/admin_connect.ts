// plus the usage-series/stats surface planned for the charts UI. Each
// RPC's comment names the HTTP route(s) it replaces. Message definitions
// live in the per-resource files of this package.
//
// Conventions:
//   - snake_case fields serialize as camelCase JSON by proto3 default. Two
//     fields keep today's non-default spelling via json_name (costUSD,
//     baseURL); everything else matches web/src/lib/types.ts as-is.
//   - Times are google.protobuf.Timestamp (RFC3339 in JSON) and spans are
//     google.protobuf.Duration ("1.5s" in JSON), replacing today's
//     timestamp strings and *_ms/_seconds ints.
//   - int64 fields (ids, token sums, row totals) surface as bigint in
//     protobuf-es and as JSON strings in proto3 JSON — a deliberate
//     migration cost over today's `number` typing.
//   - Creates and updates return the resulting resource; deletes and
//     no-payload operations return google.protobuf.Empty. (AIP-naming
//     lint rules would flag some request/response shapes here; that is the
//     documented scaled-down trade-off, not an oversight to "fix".)
//   - State toggles are optional fields on the resource's Update, not
//     verb RPCs: enable/disable, pause/resume and alias set/clear all
//     collapse into Update{Provider,Model,Key}. Absent means "leave
//     unchanged". Only genuinely one-way or job-like operations stay as
//     named methods (RevokeKey, RefreshModels).
//   - Secrets (Provider.api_key, CreateKey/RotateKey plaintext) ride an
//     unauthenticated admin surface: never log or echo request/response
//     messages, and keep /admin bound to a trusted interface as AGENTS.md
//     requires.
//   - Errors are Connect codes mapped from the store sentinels:
//     ErrBadListParam (unknown column/op, bad limit, malformed filter) →
//     invalid_argument; ErrUpstreamNotFound / ErrModelNotFound /
//     ErrProfileNotFound / ErrKeyNotFound / ErrTranscriptNotFound →
//     not_found (note: revoke/pause on unknown keys return 204 silently
//     today; the store must gain the not-found check); ErrAliasConflict →
//     already_exists; ErrProfileImmutable / ErrProfileInUse /
//     ErrProfileInvalid → failed_precondition. No error bodies are
//     modelled here.

